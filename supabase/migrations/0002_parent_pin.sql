-- ============================================================================
-- 보호자 잠금
--
-- 왜 필요한가
-- 처음에는 자녀 화면과 보호자 화면을 '메뉴를 감추는' 정도로만 나눴습니다.
-- 그런데 보호자 화면에서 세트를 열면 정답 문장이 그대로 보입니다.
-- 아이가 시험 직전에 전환해서 답을 보고 올 수 있어, 학습 앱의 신뢰가 깨집니다.
-- 그래서 전환 지점에만 잠금을 둡니다.
--
-- 자녀 PIN과 같은 방식(scrypt 해시)으로 저장하며 평문은 남기지 않습니다.
-- 잠금을 걸지 않으면 null이고, 그때는 지금처럼 그냥 전환됩니다.
-- ============================================================================

alter table families add column if not exists parent_pin_hash text;
