-- ============================================================================
-- 내장 받아쓰기 세트 기록
--
-- 왜 컬럼을 새로 두는가
-- `attempts.set_id`는 `sets` 테이블을 가리키는 외래키입니다.
-- 앱이 미리 갖고 있는 기본 문제는 `sets`에 행이 없으므로 그 컬럼을 쓸 수 없습니다.
-- 그렇다고 set_id를 비워 두면 "1급 100점"을 다시 볼 수 없고,
-- 리포트에서도 어느 세트를 풀었는지 알 수 없습니다.
--
-- 그래서 문자열 컬럼을 따로 둡니다. 값은 `g1-1-1` 같은 내장 세트 id입니다.
-- 외래키를 걸지 않는 이유는 그 목록이 DB가 아니라 코드에 있기 때문입니다.
-- ============================================================================

alter table attempts add column if not exists builtin_set_id text;

create index if not exists attempts_builtin_idx
  on attempts (child_id, builtin_set_id);
