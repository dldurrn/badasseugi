/**
 * 받침을 잘못 쓸 때 **실제로 쓰게 되는** 글자.
 *
 * 대표음(7종성)이 같으면 소리가 똑같습니다 — 「갔/갓」은 어떤 목소리로 읽어도 같습니다.
 * 다만 같은 대표음이라고 다 내놓지는 않습니다. 「했」의 후보로 「햍」을 내면
 * 아무도 안 고르므로 **문제가 공짜가 됩니다.**
 *
 * **한쪽 방향으로만 만듭니다 — 어려운 표기에서 아이가 실제로 쓰는 쉬운 표기로.**
 * 처음에는 양쪽으로 만들었다가 미리보기에서 바로 드러났습니다 —
 * 「학교」의 후보로 「핚교」가 나왔습니다. 소리는 같지만 **그렇게 쓰는 아이는 없습니다.**
 * 아무도 안 고를 후보를 내놓으면 2지선다가 1지선다가 됩니다.
 *
 * 그래서 쉬운 쪽(ㄱ ㄴ ㄷ ㄹ ㅁ ㅂ ㅇ, 그리고 ㅅ)은 **짝이 없습니다.**
 * 「갓」을 「갔」으로 잘못 쓰는 아이는 없고, 그 반대만 있습니다.
 * 물음이 서는 자리가 곧 아이가 실제로 틀리는 자리입니다.
 *
 * ㅎ 받침은 뺐습니다 — 「좋」의 짝이 될 만한 실제 낱말이 거의 없습니다.
 * ㄴ·ㄹ·ㅁ·ㅇ 홑받침도 비어 있습니다 — 소리가 저마다 달라 귀로 가려집니다.
 */
const 받침짝: Record<string, string> = {
  // 대표음 ㄱ — 「밖→박」, 「닭→닥」
  ㄲ: 'ㄱ', ㅋ: 'ㄱ', ㄳ: 'ㄱ', ㄺ: 'ㄱ',
  // 대표음 ㄷ — 저학년 오답의 대부분이 여기입니다(갔→갓, 꽃→꼿, 밭→밧)
  ㅆ: 'ㅅ', ㅈ: 'ㅅ', ㅊ: 'ㅅ', ㅌ: 'ㅅ',
  // 대표음 ㅂ — 「앞→압」, 「값→갑」
  ㅍ: 'ㅂ', ㅄ: 'ㅂ', ㄿ: 'ㅂ',
  // 겹받침 — 「앉→안」, 「넓→널」, 「삶→삼」
  ㄵ: 'ㄴ', ㄶ: 'ㄴ',
  ㄼ: 'ㄹ', ㄽ: 'ㄹ', ㄾ: 'ㄹ', ㅀ: 'ㄹ',
  ㄻ: 'ㅁ',
};

/**
 * 모음을 잘못 쓸 때 쓰게 되는 글자.
 *
 * ㅐ와 ㅔ 는 발음이 합쳐져 **어떤 목소리로 읽어도 못 가립니다**(`twin.ts` 와 같은 전제).
 * ㅚ/ㅙ/ㅞ 도 같습니다 — 「됐/됬」이 여기서 나옵니다.
 *
 * 받침과 달리 **양쪽으로 만듭니다.** 어느 쪽이 쉬운 표기랄 것이 없어
 * 「개→게」도 「게→개」도 아이가 실제로 쓰는 오류입니다.
 *
 * 초성은 넣지 않습니다. ㄱ/ㄲ, ㄷ/ㄸ 는 **귀로 가려집니다** —
 * 「가다」와 「까다」는 다르게 들립니다. 들어서 알 수 있는 것을 고르게 하면
 * 듣기 연습이 아니라 눈치 게임이 됩니다.
 */
const 모음짝: Record<string, string> = {
  ㅐ: 'ㅔ', ㅔ: 'ㅐ',
  ㅒ: 'ㅖ', ㅖ: 'ㅒ',
  ㅚ: 'ㅙ', ㅙ: 'ㅚ', ㅞ: 'ㅚ',
};

/** 겹받침 — 가장 값진 자리라 같은 문장에 여럿이면 여기를 먼저 겨눕니다 */
const 겹받침 = new Set(['ㄳ', 'ㄵ', 'ㄶ', 'ㄺ', 'ㄻ', 'ㄼ', 'ㄽ', 'ㄾ', 'ㄿ', 'ㅀ', 'ㅄ']);

/** 낮을수록 먼저 겨눕니다. 겹받침 → 받침 → 모음 */
type Rank = 0 | 1 | 2;

/**
 * 이 글자를 소리가 같은 다른 글자로 바꾸면 무엇이 되나. 바꿀 자리가 없으면 null.
 *
 * **채점 엔진이 「이건 받침 오류다」를 판정할 때 쓰는 바로 그 분해기**(`hangul.ts`)를 씁니다.
 * 같은 자를 쓰니 어긋날 수가 없습니다.
 */
export function confusable(ch: string): { char: string; rank: Rank } | null {
  const d = decompose(ch);
  if (!d) return null;

  const 다른받침 = 받침짝[d.jong];
  if (다른받침) {
    return {
      char: compose({ ...d, jong: 다른받침 }),
      rank: 겹받침.has(d.jong) ? 0 : 1,
    };
  }

  const 다른모음 = 모음짝[d.jung];
  if (다른모음) return { char: compose({ ...d, jung: 다른모음 }), rank: 2 };

  return null;
}

/**
 * 낱말 하나의 후보. 정답 포함 **둘**이고, 못 만들면 정답 하나뿐입니다.
 *
 * **오답은 한 자리만 바꿉니다.** 두 군데를 바꾸면 「어쩐지 더 틀려 보이는 쪽」이 생겨
 * 소리를 안 듣고도 걸러집니다.
 *
 * 후보를 둘로 둔 것도 같은 이유입니다. 한 낱말에서 그럴듯한 오답은 보통 하나뿐이고,
 * 억지로 셋을 채우면 아무도 안 고르는 글자가 끼어 문제가 공짜가 됩니다.
 * 찍으면 절반이 맞지만 **이 모드는 아무것도 기록하지 않으므로** 잃는 것이 없습니다.
 *
 * @param pick 무작위 자리를 고르는 함수. 테스트에서 고정할 수 있게 받습니다(`twin.ts` 와 같은 방식).
 */
export function wordOptions(
  word: string,
  pick: (n: number) => number = 무작위,
): string[] {
  const chars = [...word];

  // 바꿀 수 있는 자리를 모두 찾아 가장 값진 갈래만 남깁니다.
  const 자리들 = chars
    .map((ch, i) => ({ i, found: confusable(ch) }))
    .filter((x): x is { i: number; found: { char: string; rank: Rank } } => x.found !== null);
  if (자리들.length === 0) return [word];

  const 가장값진 = Math.min(...자리들.map((x) => x.found.rank));
  const 후보자리 = 자리들.filter((x) => x.found.rank === 가장값진);
  const 고른자리 = 후보자리[뽑기(후보자리.length, pick)];

  const 오답 = [...chars];
  오답[고른자리.i] = 고른자리.found.char;

  return 섞기([word, 오답.join('')], pick);
}

