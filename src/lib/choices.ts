function 무작위(n: number): number {
  return Math.floor(Math.random() * n);
}

/** 주입받은 `pick` 이 범위를 벗어나도 안전하게 */
function 뽑기(n: number, pick: (n: number) => number): number {
  return Math.min(n - 1, Math.max(0, pick(n)));
}

/** 정답이 늘 앞에 오면 아이가 소리를 안 듣고 첫째 것만 누릅니다 */
function 섞기(items: string[], pick: (n: number) => number): string[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = 뽑기(i + 1, pick);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
