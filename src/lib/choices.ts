/**
 * 어절에서 떼어 낼 수 있는 꼬리. **긴 것부터 봅니다.**
 *
 * 두 글자 이상인 것을 먼저 적은 이유는 낱말 끝에 우연히 걸릴 일이 거의 없기 때문입니다.
 * 한 글자짜리는 위험합니다 — 「이」를 떼면 「목걸이」가 「목걸 | 이」가 되고,
 * 「고」를 떼면 「냉장고」가 「냉장 | 고」가 됩니다. 아이가 「목걸」이라는 조각을 보게 됩니다.
 * 그래서 **한 글자짜리는 낱말 끝에 잘 안 오는 것만** 골라 담았습니다
 * (이·도·고·만·지를 일부러 뺐습니다).
 */
const 꼬리들 = [
  // 조사 — 두 글자 이상
  '이에요', '에서', '에게', '한테', '으로', '까지', '부터', '처럼', '보다', '마다',
  '에는', '에도', '이나', '라도', '밖에', '예요', '이야', '이다',
  // 어미 — 두 글자 이상
  '습니다', '합니다', '했어요', '았어요', '었어요', '였어요', '웠어요', '겠어요',
  '세요', '어요', '아요', '해요', '지만', '어서', '해서', '려고', '면서', '니까', '는데',
  // 조사 — 한 글자. 낱말 끝에 잘 안 오는 것만
  '을', '를', '은', '는', '가', '에', '와', '과', '의',
];

/** 꼬리를 떼고 남는 줄기의 최소 길이. 「포도」가 「포 | 도」가 되는 것을 막습니다 */
const 줄기최소 = 2;

/**
 * 어절 하나를 「줄기 + 꼬리」로 자릅니다. 자를 수 없으면 통째로 하나.
 *
 * **한 어절은 한 번만 자릅니다.** 잘게 쪼갤수록 조각이 낱말처럼 안 읽힙니다.
 *
 * 잘못 잘려도 최악이 「붙여요가 답인 자리가 하나 더 생기는 것」이라
 * 완성되는 문장은 그대로입니다.
 */
export function splitWord(word: string): string[] {
  const chars = [...word];
  // 한글로 끝나지 않으면 건드리지 않습니다(따옴표·부호가 붙은 조각).
  if (!decompose(chars[chars.length - 1] ?? '')) return [word];

  for (const 꼬리 of 꼬리들) {
    if (!word.endsWith(꼬리)) continue;
    const 줄기 = chars.slice(0, chars.length - [...꼬리].length);
    if (줄기.length < 줄기최소) continue;
    // 줄기가 온전한 한글이어야 합니다. 「"안녕」 같은 조각을 만들지 않습니다.
    if (!줄기.every((c) => decompose(c))) continue;
    return [줄기.join(''), 꼬리];
  }

  return [word];
}

