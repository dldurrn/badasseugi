export type AskKind = 'word' | 'join' | 'end';

export interface Ask {
  kind: AskKind;
  /** 정답을 포함해 화면에 그릴 차례대로 */
  options: string[];
}

export interface Segment {
  /**
   * 이 조각이 문장에 더하는 값.
   * **모두 이어 붙이면 원래 문장이 됩니다** — 테스트가 이 왕복을 지킵니다.
   */
  text: string;
  /** 물을 것이 없으면 null. 그냥 놓입니다 */
  ask: Ask | null;
}

/** 이음 — 값이 곧 문장에 더해지는 것이라 라벨은 화면이 붙입니다 */
export const JOIN_SPACE = ' ';
export const JOIN_NONE = '';
export const JOIN_COMMA = ', ';

/**
 * 이음 후보는 **언제나 셋 다** 내놓습니다.
 *
 * 쉼표가 있을 때만 셋을 내놓으면 개수가 답을 흘립니다.
 * 그리고 쉼표는 **쉼으로 들리므로** 매번 물어도 정직한 듣기 문제입니다.
 *
 * 자리는 고정입니다. 낱말 후보와 달리 내용이 늘 같아서, 자리까지 섞으면
 * 다시 읽느라 손이 헛나갑니다 — 그건 생각이 아니라 성가심입니다.
 */
export const JOIN_OPTIONS = [JOIN_SPACE, JOIN_NONE, JOIN_COMMA];

export function joinLabel(value: string): string {
  if (value === JOIN_SPACE) return '띄어요';
  if (value === JOIN_NONE) return '붙여요';
  return ',';
}

/** 끝 문장부호. 마침표·물음표·느낌표는 **억양으로 들리므로** 정직한 듣기 문제입니다 */
export const END_OPTIONS = ['.', '?', '!'];

/**
 * 문장을 걸음으로 폅니다.
 *
 * 문장 가운데의 마침표(20단계의 두 문장짜리)는 낱말 조각에 그대로 붙여 둡니다.
 * 거기까지 물으면 걸음이 너무 잘게 쪼개지고, 두 문장을 잇는 것이 그 단계의 목적이라
 * 「.」 하나를 따로 묻는 것이 배움에 보태는 것이 없습니다.
 */
export function buildSegments(
  sentence: string,
  pick: (n: number) => number = 무작위,
): Segment[] {
  const s = normalize(sentence);
  if (!s) return [];

  /*
    끝 문장부호를 떼어 마지막 걸음으로 둡니다.

    앞 글자에 **붙어 있을 때만** 뗍니다. 「가자 .」처럼 띄어져 있으면 그대로 두어야
    이어 붙였을 때 원래 문장으로 돌아옵니다 — 왕복이 깨지면 아이가 고른 것과
    화면에 그려지는 것이 갈립니다.
  */
  const 끝 = /[^\s][.?!]$/.test(s) ? s.slice(-1) : null;
  const 몸통 = 끝 ? s.slice(0, -1) : s;

  const 어절들 = 몸통.split(' ').filter((w) => w.length > 0);
  const segments: Segment[] = [];

  어절들.forEach((어절, i) => {
    const 마지막어절 = i === 어절들.length - 1;

    // 쉼표는 낱말에서 떼어 **이음**으로 옮깁니다. 이음 후보에 쉼표가 있어야 물을 수 있습니다.
    const 쉼표 = !마지막어절 && 어절.endsWith(',');
    const 낱말 = 쉼표 ? 어절.slice(0, -1) : 어절;
    const 이음 = 마지막어절 ? null : 쉼표 ? JOIN_COMMA : JOIN_SPACE;

    const 조각들 = splitWord(낱말);
    조각들.forEach((조각, j) => {
      const options = wordOptions(조각, pick);
      segments.push({ text: 조각, ask: options.length > 1 ? { kind: 'word', options } : null });

      // 조각 사이는 「붙여요」가 정답인 이음입니다. 여기가 조사·어미를 가르치는 자리입니다.
      const 뒤 = j < 조각들.length - 1 ? JOIN_NONE : 이음;
      if (뒤 !== null) {
        segments.push({ text: 뒤, ask: { kind: 'join', options: JOIN_OPTIONS } });
      }
    });
  });

  if (끝) segments.push({ text: 끝, ask: { kind: 'end', options: END_OPTIONS } });

  return segments;
}

/**
 * 물을 것이 하나라도 있는 문장인가.
 *
 * **없으면 이 모드에서 건너뜁니다.** 「포도」·「안경」처럼 받침이 ㄴ·ㅇ뿐이고
 * 낱말이 하나면 귀로 못 가릴 자리가 정말로 하나도 없습니다 — 그건 버그가 아니라
 * 그 문장이 쉽다는 뜻입니다. 물음이 뜨는 자리가 곧 값이 있는 자리입니다.
 */
export function hasChoices(sentence: string): boolean {
  return buildSegments(sentence, () => 0).some((s) => s.ask !== null);
}

/**
 * 지금까지 고른 것이 차지하는 칸.
 *
 * `toCells` 는 채점을 위해 **끝의 공백을 자릅니다.** 여기서는 그러면 안 됩니다 —
 * 「띄어요」를 고른 순간 커서가 제자리에 머물러 눌러도 아무 일도 안 일어난 것처럼 보입니다.
 * 쉼표 뒤 공백은 그대로 흡수합니다(원고지 규칙, `absorbsFollowingSpace`).
 */
export function prefixCells(prefix: string): string[] {
  const cells = toCells(prefix);
  const 끝 = prefix[prefix.length - 1];
  const 그앞 = prefix[prefix.length - 2];
  if (끝 === ' ' && !(그앞 !== undefined && absorbsFollowingSpace(그앞))) cells.push(EMPTY);
  return cells;
}

/** 다음에 물어볼 걸음. 물을 것이 없는 조각은 그냥 지나칩니다 */
export function nextAsk(segments: Segment[], from: number): number {
  let i = Math.max(0, from);
  while (i < segments.length && segments[i].ask === null) i += 1;
  return i;
}

