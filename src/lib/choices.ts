/**
 * 골라서 익히기 — 문장을 **처음부터 끝까지 하나씩 골라** 만들어 나갑니다.
 *
 * 키보드가 없는 자리(등교길, 시험 직전)에서 쓰라고 만든 모드입니다.
 * 소리는 이미 폰에서 나니 **쓰는 쪽만 손가락으로 대신합니다.**
 *
 * **이 파일에는 AI 도 네트워크도 없습니다.** `twin.ts` 의 맞춤법 짝과 같은 층입니다 —
 * 규칙과 데이터만으로 후보를 만듭니다. 원가 0원, 즉시, 늘 같은 결과.
 *
 * ─────────────────────────────────────────────────────────────
 * 왜 「빈 칸 채우기」가 아니라 「이어 고르기」인가
 *
 * 처음에는 문장을 다 보여 주고 함정 칸 두어 개만 비우려 했습니다. 바꿨습니다.
 *
 *  1. **오류가 사는 단위가 어절입니다.** 「갔/갓」은 글자 문제가 아니라 과거 시제 ㅆ 의 문제이고,
 *     「학교에/학교애」는 조사 에 의 문제입니다. 「에/애」만 떼어 보여 주면 왜 그런지 볼 자리가 없습니다.
 *     이 프로젝트는 이미 같은 판단을 한 적이 있습니다 — 개/게를 받아쓰기에서 홀로 안 쓰고
 *     **문맥이 있는 맞춤법 쪽으로 보낸 것**이 그것입니다.
 *  2. **쓰는 순서와 같습니다.** 받아쓰기는 왼쪽에서 오른쪽으로 만들어 나가는 일입니다.
 *     다 보여 주고 구멍을 메우게 하면 교정 연습이 되고, 이어 고르게 하면 생산 연습이 됩니다.
 *  3. **정답 문장을 미리 안 보여 줍니다.** 문장은 아이가 고른 만큼만 나타납니다.
 *
 * ─────────────────────────────────────────────────────────────
 * 걸음은 셋뿐입니다
 *
 *   ① 낱말   학교에  ←→  학교애      (귀로 못 가리는 자리 하나만 바꾼 것)
 *   ② 이음   띄어요 · 붙여요 · ,      (낱말 사이마다 **매번**)
 *   ③ 끝     .  ·  ?  ·  !
 *
 * **이음을 매번 묻는 이유**는 「물음이 뜬다는 것 자체가 답을 흘리기」 때문입니다.
 * 헷갈리는 자리에서만 물으면 아이는 「물어보네? 그럼 어려운 데구나」로 읽습니다.
 *
 * 그러려면 낱말을 **어절보다 잘게** 잘라야 합니다. 어절 사이에서만 물으면
 * 답이 언제나 「띄어요」라서, 매번 물어도 아무것도 안 가르칩니다.
 * 그래서 체언+조사, 용언+어미도 자릅니다(`splitWord`) — 「학교 | 에」의 답은 붙여요입니다.
 * 저학년이 가장 많이 틀리는 두 가지가 정확히 이 둘입니다:
 * 「학교 **에** 갔어요」(조사를 떼어 씀)와 「할**수**있어요」(의존명사를 붙여 씀).
 *
 * ─────────────────────────────────────────────────────────────
 * **아무것도 저장하지 않습니다.** 점수도, 오답노트 별도, 이력도.
 * 2지선다는 찍어서 절반이 맞는데 그건 절대 원칙 5가 막으려던 바로 그것입니다.
 * 기록에 안 쓰기 때문에 2지선다를 써도 되는 것이라, 이 둘은 한 몸입니다.
 */

