/**
 * 무료와 유료를 가르는 규칙 — **아직 켜지 않았습니다.**
 *
 * 지금은 모두 유료와 같은 것을 씁니다(`PLAN_ENABLED = false`).
 * 규칙을 먼저 한 곳에 적어 두는 이유는, 나중에 결제를 붙일 때
 * 화면 여기저기에 조건문이 흩어지지 않게 하려는 것입니다.
 * 켜는 것은 이 파일의 값 하나를 바꾸는 일이 됩니다.
 *
 * ─────────────────────────────────────────────────────────────
 * 무엇을 잠그고 무엇을 안 잠그나
 *
 * **원가로 가르지 않습니다.** 재어 보니 원가가 거의 안 듭니다 —
 * 문장 평균 9.2자, 한 세션 10문장이면 이어 읽기 92자입니다.
 * 다시 듣기는 브라우저가 소리를 담아 두어 공짜이고,
 * 한 가족이 한 달에 2,000~8,000자를 씁니다. Google 무료 한도가 월 100만 자입니다.
 * 즉 「많이 쓰면 손해」인 구조가 아니라 고정비가 거의 전부입니다.
 *
 * 그래서 **부모가 무엇에 돈을 낼 만한가**로 가릅니다.
 *
 *   원고지는 절대 안 잠급니다.
 *     이건 제품의 정체성입니다. 빼면 남는 건 「소리 나는 받아쓰기 앱」이고 그건 흔합니다.
 *     무료 사용자에게 더 나쁜 학습 도구를 주는 셈이라 나중에 설명하기 부끄러워집니다.
 *     그리고 원가가 0원입니다. 잠글 이유가 하나도 없습니다.
 *
 *   목소리는 전면 차단하지 않습니다.
 *     소리를 막으면 받아쓰기가 아예 성립하지 않습니다. 받아쓸 게 없으니까요.
 *     대신 **하루 몇 세션**으로 셉니다. 성실하게 쓰는 집은 한도에 안 닿습니다.
 *     한도는 벌이 아니라 「더 필요하면 그때」를 알리는 장치입니다.
 *
 *   사진으로 문제 넣기가 가장 좋은 유료 기능입니다.
 *     부모가 가장 아쉬워하는 시간을 삽니다 — 문제지 한 장 타이핑에 10분.
 *     유일하게 진짜 원가가 붙고, 없어도 앱이 성립하며(직접 입력이 있으니),
 *     무엇보다 **아이 경험을 건드리지 않습니다.**
 */

export type Plan = 'free' | 'paid';

/**
 * 아직 켜지 않았습니다.
 *
 * 결제가 없는 상태에서 한도만 걸면, 돈을 낼 길도 없이 막히는 사람이 생깁니다.
 * 결제를 붙인 뒤에 이 값을 true 로 바꿉니다.
 */
export const PLAN_ENABLED = false;

export interface Limits {
  /** 하루에 서버 목소리로 풀 수 있는 세션 수. null 이면 제한 없음 */
  sessionsPerDay: number | null;
  /** 만들 수 있는 자녀 프로필 수 */
  children: number;
  /** 사진으로 문제 넣기 */
  photoInput: boolean;
  /** 리포트를 몇 주까지 거슬러 보나. null 이면 전부 */
  reportWeeks: number | null;
}

export const LIMITS: Record<Plan, Limits> = {
  /*
    하루 2세션은 넉넉합니다. 매일 시키는 집도 보통 하루 1세션입니다.
    리포트 1주는 「이번 주」만 — 지난주와 견주는 것이 유료의 값어치입니다.
  */
  free: { sessionsPerDay: 2, children: 1, photoInput: false, reportWeeks: 1 },
  paid: { sessionsPerDay: null, children: 4, photoInput: true, reportWeeks: null },
};

/**
 * 지금 이 집이 쓸 수 있는 것.
 *
 * `PLAN_ENABLED` 가 꺼져 있는 동안은 모두 유료와 같습니다 —
 * 아직 돈을 낼 길이 없는데 막으면 안 되니까요.
 */
export function limitsFor(plan: Plan): Limits {
  return PLAN_ENABLED ? LIMITS[plan] : LIMITS.paid;
}

/**
 * 이 집의 요금제.
 *
 * 결제가 붙으면 여기서 `families` 행을 보게 됩니다.
 * 그때까지는 모두 무료입니다 — 다만 위의 `limitsFor` 가 아직 막지 않습니다.
 */
export function planOf(_family: unknown): Plan {
  return 'free';
}
