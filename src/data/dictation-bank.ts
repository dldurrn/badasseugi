export function findBuiltinSet(id: string): BuiltinSet | null {
  return DICTATION_BANK.find((s) => s.id === id) ?? null;
}

/** DB의 세트 id(uuid)와 섞이지 않도록 형태로 구분합니다. */
export function isBuiltinSetId(id: string): boolean {
  return /^lv\d+$/.test(id);
}
